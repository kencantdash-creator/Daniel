function initials($name) {
    $parts = preg_split('/\s+/', trim($name));
    $first = mb_substr($parts[0], 0, 1);
    $last = count($parts) > 1 ? mb_substr(end($parts), 0, 1) : '';
    return strtoupper($first . $last);
}

function office_status(PDO $pdo) {
    $st = $pdo->prepare('SELECT * FROM office_hours WHERE day_label = ?');
    $st->execute([date('l')]);
    $row = $st->fetch();
    if (!$row || !$row['open_time']) return ['open' => false, 'text' => 'Closed today'];
    $now = date('H:i:s');
    if ($now >= $row['open_time'] && $now < $row['close_time']) {
        return ['open' => true, 'text' => 'Open now until ' . fmt_time($row['close_time'])];
    }
    return ['open' => false, 'text' => 'Closed now. Today ' . fmt_time($row['open_time']) . ' to ' . fmt_time($row['close_time'])];
}

